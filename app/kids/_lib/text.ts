export function kidError(lang: Lang, message: string | undefined, fallback: string) {
  if (!message) return fallback;
  if (lang === "nb") return message;
  return ERRORS[message]?.[lang] ?? fallback;
}

// Tekst for et merke ut fra nøkkelen (serveren sender norsk tekst, men også
// nøkkel og mål, så barnesiden kan vise merket på riktig språk).
export function badgeText(t: KidText, b: { key: string; title: string; hint: string; need?: number; task?: string | null }): [string, string] {
  const need = b.need ?? 0;
  if (b.key === "first") return t.badgeFirst as [string, string];
  if (["ten", "fifty", "hundred"].includes(b.key) || /^tasks\d+$/.test(b.key)) return t.badgeTotal(need) as [string, string];
  if (/^kr\d+$/.test(b.key)) return t.badgeKr(Math.round(need / 100)) as [string, string];
  if (b.key === "saver") return t.badgeSaver as [string, string];
  if (b.key === "wish") return t.badgeWish as [string, string];
  if (/^streak\d+$/.test(b.key)) return t.badgeStreak(need) as [string, string];
  if (b.key === "expert") return t.badgeExpert(b.task ?? null) as [string, string];
  return [b.title, b.hint];
}
